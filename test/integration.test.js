const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { randomBytes } = require('node:crypto');
const { Sftp } = require('../src/backend/sftp');
const { Transfers } = require('../src/backend/transfers');
const { LocalFiles } = require('../src/backend/local');
const { DesktopFiles } = require('../src/backend/desktop-files');
const { deleteEntries, renameEntry } = require('../src/backend/files');
const { createAskpass } = require('../src/backend/askpass');
const { testServer } = require('./helpers');
test('OpenSSH + native askpass + SFTP: authentication, listing, recursive copies, conflicts and cancellation', {timeout:120000},async t => {
  const root = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(),'explorer-sftp-')));
  t.after(() => fs.rm(root,{recursive:true,force:true}));
  const alpha = path.join(root,'alpha'), beta = path.join(root,'beta');
  await fs.mkdir(path.join(alpha,'资料','子目录'),{recursive:true}); await fs.mkdir(beta);
  const data = randomBytes(1024*1024+17);
  await fs.writeFile(path.join(alpha,'资料','中文 file.bin'),data);
  await fs.writeFile(path.join(alpha,'资料','子目录','zero.txt'),'');
  await fs.writeFile(path.join(alpha,'standalone.txt'),'new contents');
  const server = await testServer({alpha,beta}); t.after(() => server.close());
  const prompts = [];
  const bridge = await createAskpass(path.resolve('resources/askpass.exe'),async prompt => { prompts.push(prompt.kind); return prompt.kind === 'trust' ? 'yes' : 'test-password'; });
  t.after(() => bridge.close());
  const config = path.join(root,'config');
  await fs.writeFile(config,`Host alpha beta\n HostName 127.0.0.1\n Port ${server.port}\n RemoteCommand echo interactive-only\n PreferredAuthentications password\n UserKnownHostsFile "${path.join(root,'known_hosts').replaceAll('\\','/')}"\nHost alpha\n User alpha\nHost beta\n User beta\n`);
  const a = Sftp.connect('alpha',config,bridge.env,{connectTimeout:15000}), b = Sftp.connect('beta',config,bridge.env,{connectTimeout:15000});
  t.after(() => { a.close(); b.close(); });
  await Promise.all([a.ready,b.ready]);
  assert.ok(prompts.includes('trust')); assert.ok(prompts.includes('secret'));
  assert.equal(await a.realpath('.'),'/');
  const listing = await a.list('/'); assert.deepEqual(listing.map(e => e.name),['资料','standalone.txt']);
  const sessions = {local:{sftp:new LocalFiles(),alias:'本地电脑',identity:'local'},a:{sftp:a,alias:'alpha',identity:'alpha'},b:{sftp:b,alias:'beta',identity:'beta'}};
  const listeners = new Map(); let decision = 'skip'; let cancelWhenRunning = false; let lastProgress = 0;
  const transfers = new Transfers({ getSession:id => sessions[id], ask:async()=>decision, emit:job => {
    if (job.bytes) lastProgress = job.bytes;
    if (cancelWhenRunning && job.status === 'running' && job.bytes > 0) transfers.cancel(job.id);
    if (['done','failed','cancelled'].includes(job.status)) listeners.get(job.id)?.(job);
  } });
  function run(paths,targetPath='/',sourceId='a',targetId='b') { const id=transfers.start({sourceId,targetId,paths,targetPath}); return new Promise(resolve=>listeners.set(id,resolve)); }
  const copied = await run(['/资料']);
  assert.equal(copied.status,'done',copied.error); assert.equal(copied.completed,2); assert.equal(copied.bytes,data.length); assert.ok(lastProgress>0);
  assert.deepEqual(await fs.readFile(path.join(beta,'资料','中文 file.bin')),data);
  assert.equal((await fs.stat(path.join(beta,'资料','子目录','zero.txt'))).size,0);
  assert.deepEqual(await fs.readFile(path.join(alpha,'资料','中文 file.bin')),data,'source remains untouched');
  await fs.writeFile(path.join(beta,'standalone.txt'),'original');
  const skipped = await run(['/standalone.txt']); assert.equal(skipped.status,'done'); assert.equal(skipped.skipped,1); assert.equal(await fs.readFile(path.join(beta,'standalone.txt'),'utf8'),'original');
  decision='replace'; const replaced=await run(['/standalone.txt']); assert.equal(replaced.status,'done',replaced.error); assert.equal(await fs.readFile(path.join(beta,'standalone.txt'),'utf8'),'new contents');
  server.allowOverwrite(false); await fs.writeFile(path.join(beta,'standalone.txt'),'keep this original');
  const unsupported=await run(['/standalone.txt']); assert.equal(unsupported.status,'failed'); assert.match(unsupported.error,/原文件已保留/); assert.equal(await fs.readFile(path.join(beta,'standalone.txt'),'utf8'),'keep this original');
  server.allowOverwrite(true);
  const same = await run(['/standalone.txt'],'/','a','a'); assert.equal(same.status,'done'); assert.equal(same.skipped,1); assert.equal(same.completed,0);
  assert.equal((await transfers.inspect({sourceId:'a',targetId:'a',paths:['/standalone.txt'],targetPath:'/'})).sameDirectory,true);
  assert.equal((await transfers.inspect({sourceId:'a',targetId:'b',paths:['/standalone.txt'],targetPath:'/'})).sameDirectory,false);
  const alias = Sftp.connect('alpha',config,bridge.env,{connectTimeout:15000}); t.after(()=>alias.close()); await alias.ready;
  sessions.alias={sftp:alias,alias:'other-alpha-alias',identity:'alpha'};
  assert.equal((await transfers.inspect({sourceId:'a',targetId:'alias',paths:['/资料','/standalone.txt'],targetPath:'/'})).sameDirectory,true);
  await fs.mkdir(path.join(alpha,'copied')); const readsBefore=server.counters.reads, writesBefore=server.counters.writes;
  const remoteCopy = await run(['/资料','/standalone.txt'],'/copied','a','alias');
  assert.equal(remoteCopy.status,'done',remoteCopy.error); assert.equal(remoteCopy.mode,'server'); assert.equal(remoteCopy.completed,3);
  assert.deepEqual(await fs.readFile(path.join(alpha,'copied','资料','中文 file.bin')),data);
  assert.equal((await fs.stat(path.join(alpha,'copied','资料','子目录','zero.txt'))).size,0);
  assert.equal(server.counters.reads,readsBefore,'same-server contents never use SFTP READ');
  assert.equal(server.counters.writes,writesBefore,'copy-data never sends contents back through SFTP WRITE');
  assert.ok(server.counters.copies >= 2); assert.equal(server.counters.execs,0,'supported servers need no second SSH command');
  decision='skip'; const sameConflict=await run(['/standalone.txt'],'/copied','a','alias'); assert.equal(sameConflict.skipped,1);
  await fs.writeFile(path.join(alpha,'copied','standalone.txt'),'older remote'); decision='replace';
  assert.equal((await run(['/standalone.txt'],'/copied','a','alias')).status,'done');
  assert.equal(await fs.readFile(path.join(alpha,'copied','standalone.txt'),'utf8'),'new contents');
  await fs.symlink(path.join(alpha,'copied'),path.join(alpha,'directory-alias'),process.platform === 'win32' ? 'junction' : 'dir');
  assert.equal((await transfers.inspect({sourceId:'a',targetId:'alias',paths:['/directory-alias/standalone.txt'],targetPath:'/copied/.'})).sameDirectory,true,'canonical directory aliases are no-ops');
  const canonicalSame=await run(['/directory-alias/standalone.txt'],'/copied','a','alias');
  assert.equal(canonicalSame.status,'done'); assert.equal(canonicalSame.skipped,1);
  await fs.mkdir(path.join(alpha,'remote-cancel')); cancelWhenRunning=true;
  const remoteCancelled=await run(['/资料/中文 file.bin'],'/remote-cancel','a','alias');
  assert.equal(remoteCancelled.status,'cancelled'); assert.deepEqual(await fs.readdir(path.join(alpha,'remote-cancel')),[]); cancelWhenRunning=false;
  const oddName="中文 ' $(echo ignored); file.txt"; await fs.writeFile(path.join(alpha,oddName),'quoted copy');
  server.allowCopyData(false); const fallbackReads=server.counters.reads;
  const fallback=await run(['/'+oddName],'/copied','a','alias');
  assert.equal(fallback.status,'done',fallback.error); assert.equal(await fs.readFile(path.join(alpha,'copied',oddName),'utf8'),'quoted copy');
  assert.equal(server.counters.reads,fallbackReads,'fallback does not download contents'); assert.ok(server.counters.execs>0);
  server.allowExec(false); await fs.mkdir(path.join(alpha,'unsupported-copy'));
  const noCapability=await run(['/standalone.txt'],'/unsupported-copy','a','alias');
  assert.equal(noCapability.status,'failed'); assert.match(noCapability.error,/服务器端复制失败/); assert.deepEqual(await fs.readdir(path.join(alpha,'unsupported-copy')),[]);
  server.allowExec(true);
  await fs.mkdir(path.join(alpha,'cancel-old-server')); server.execDelay(250);
  const execsBefore=server.counters.execs;
  const fallbackId=transfers.start({sourceId:'a',targetId:'alias',paths:['/standalone.txt'],targetPath:'/cancel-old-server'});
  const fallbackFinished=transfers.wait(fallbackId);
  for (let i=0; i<100 && server.counters.execs === execsBefore; i++) await new Promise(resolve=>setTimeout(resolve,10));
  assert.ok(server.counters.execs>execsBefore); transfers.cancel(fallbackId);
  assert.equal((await fallbackFinished).status,'cancelled');
  await new Promise(resolve=>setTimeout(resolve,300));
  assert.deepEqual(await fs.readdir(path.join(alpha,'cancel-old-server')),[],'cancelled old-server copies remove temporary files');
  server.execDelay(0); server.allowCopyData(true);
  const descendant = await run(['/资料'],'/资料/子目录','a','a'); assert.equal(descendant.status,'failed'); assert.match(descendant.error,/内部/);
  const localRoot = path.join(root,'local'), downloadRoot = path.join(root,'download');
  await fs.mkdir(path.join(localRoot,'上传目录','子目录'),{recursive:true}); await fs.mkdir(downloadRoot);
  await fs.writeFile(path.join(localRoot,'上传目录','中文 file.bin'),data);
  await fs.writeFile(path.join(localRoot,'上传目录','子目录','zero.txt'),'');
  const upload = await run([path.join(localRoot,'上传目录')],'/','local','b');
  assert.equal(upload.status,'done',upload.error); assert.equal(upload.completed,2);
  assert.deepEqual(await fs.readFile(path.join(beta,'上传目录','中文 file.bin')),data);
  const download = await run(['/上传目录'],downloadRoot,'b','local');
  assert.equal(download.status,'done',download.error);
  assert.deepEqual(await fs.readFile(path.join(downloadRoot,'上传目录','中文 file.bin')),data);
  assert.equal((await fs.stat(path.join(downloadRoot,'上传目录','子目录','zero.txt'))).size,0);
  await fs.writeFile(path.join(downloadRoot,'standalone.txt'),'local original');
  decision='skip'; const downloadSkip = await run(['/standalone.txt'],downloadRoot,'a','local');
  assert.equal(downloadSkip.skipped,1); assert.equal(await fs.readFile(path.join(downloadRoot,'standalone.txt'),'utf8'),'local original');
  decision='replace'; const downloadReplace = await run(['/standalone.txt'],downloadRoot,'a','local');
  assert.equal(downloadReplace.status,'done',downloadReplace.error); assert.equal(await fs.readFile(path.join(downloadRoot,'standalone.txt'),'utf8'),'new contents');
  const localSame = await run([path.join(downloadRoot,'standalone.txt')],downloadRoot,'local','local');
  assert.equal(localSame.status,'done'); assert.equal(localSame.skipped,1);
  const localInside = await run([path.join(localRoot,'上传目录')],path.join(localRoot,'上传目录','子目录'),'local','local');
  assert.equal(localInside.status,'failed'); assert.match(localInside.error,/内部/);
  assert.equal(await deleteEntries(b,'/',['上传目录']),4);
  assert.equal(await b.exists('/上传目录'),null);
  assert.equal(await deleteEntries(sessions.local.sftp,downloadRoot,['上传目录']),4);
  assert.equal(await sessions.local.sftp.exists(path.join(downloadRoot,'上传目录')),null);
  await renameEntry(b,'/','standalone.txt','renamed.txt');
  assert.equal(await fs.readFile(path.join(beta,'renamed.txt'),'utf8'),'keep this original');
  const desktopFiles = new DesktopFiles({directory:path.join(root,'desktop-files'),local:sessions.local.sftp,transfers,getSession:id=>sessions[id]});
  const prepared = await desktopFiles.prepare({id:'a',paths:['/standalone.txt','/资料']});
  assert.equal(prepared.length,2);
  assert.equal(await fs.readFile(prepared.find(p=>p.endsWith('standalone.txt')),'utf8'),'new contents');
  assert.deepEqual(await fs.readFile(path.join(prepared.find(p=>p.endsWith('资料')),'中文 file.bin')),data);
  const preparedDirectory = path.dirname(prepared[0]);
  const oldTime = new Date(Date.now()-172800000); await fs.utimes(preparedDirectory,oldTime,oldTime);
  await fs.mkdir(path.join(desktopFiles.directory,'other-folder'));
  await desktopFiles.cleanup(); assert.deepEqual(await fs.readdir(desktopFiles.directory),['other-folder'],'cleanup only removes aged app exports');
  await assert.rejects(desktopFiles.remove(root),/无效/);
  cancelWhenRunning=true;
  await assert.rejects(desktopFiles.prepare({id:'a',paths:['/资料/中文 file.bin']}),/取消/);
  assert.deepEqual(await fs.readdir(desktopFiles.directory),['other-folder'],'cancelled exports remove staging files');
  const cancelledDownload = await run(['/资料/中文 file.bin'],downloadRoot,'a','local');
  assert.equal(cancelledDownload.status,'cancelled');
  assert.deepEqual(await fs.readdir(downloadRoot),['standalone.txt'],'cancelled local downloads clean up temporary files');
  await fs.mkdir(path.join(beta,'cancelled')); cancelWhenRunning=true;
  const cancelled=await run(['/资料/中文 file.bin'],'/cancelled'); assert.equal(cancelled.status,'cancelled');
  assert.deepEqual(await fs.readdir(path.join(beta,'cancelled')),[],'cancelled file and temp are removed');
  assert.ok(!(await fs.readdir(beta)).some(n=>n.endsWith('.part')));
});
